  p.estado_civil,
  p.n_hijos,
  p.nivel_academico,
  p.carrera,
  p.nacionalidad,
  p.lugar_residencia,
  p.distrito_residencia,
  p.direccion_domicilio,
  n.periodo_reclutado,
  n.semana_trabajo,
  r.nombre_completo             AS reclutador,
  s.nombre                      AS sede,
  c.nombre                      AS campana,
  n.reclutador_id,
  n.sede_id,
  n.campana_id,
  n.fuente_oferta,
  n.observacion_reclutamiento,
  n.exp_call_center,
  n.exp_tipo_campana,
  n.exp_tiempo_campana,
  n.exp_otra,
  n.exp_tiempo_otra,
  n.grupo_codigo,
  n.modalidad::TEXT             AS modalidad,
  n.condicion,
  n.horario_gestion,
  n.descanso,
  n.envio_dni,
  n.test_psicologico,
  n.validacion_pc,
  n.evaluacion_dia_0,
  n.fecha_inicio_capacitacion,
  n.fecha_fin_capacitacion,
  n.fecha_conexion_ojt,
  n.fecha_conexion_op,
  n.pago_capacitacion,
  n.tipo_contratacion,
  n.razon_social,
  n.remuneracion,
  n.bono_variable,
  n.bono_movilidad,
  n.bono_bienvenida,
  n.bono_permanencia,
  n.bono_asistencia_perfecta,
  n.cargo_contractual,
  n.dia_0,
  n.dia_0_obs,
  n.status_dia_1,
  n.dia_1,
  n.dia_1_obs,
  n.estado::TEXT                AS estado,
  n.activo,
  p.created_at,
  n.updated_at
FROM nominas n
JOIN postulantes p ON p.documento = n.postulante_documento
LEFT JOIN reclutadores r ON r.id = n.reclutador_id
LEFT JOIN sedes s ON s.id = n.sede_id
LEFT JOIN campanas c ON c.id = n.campana_id
WHERE n.activo = TRUE;

