-- ── CATÁLOGOS (dimensiones) ─────────────────────────────────
CREATE TABLE IF NOT EXISTS sedes (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre     VARCHAR(100) NOT NULL UNIQUE,
  activa     BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS campanas (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre     VARCHAR(150) NOT NULL UNIQUE,
  segmento   VARCHAR(100),
  supervisor VARCHAR(150),
  meta_grupal INTEGER DEFAULT 0,
  activa     BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS reclutadores (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_completo VARCHAR(200) NOT NULL UNIQUE,
  activo          BOOLEAN NOT NULL DEFAULT TRUE,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS campana_reclutadores (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campana_id      BIGINT NOT NULL REFERENCES campanas(id) ON DELETE CASCADE,
  reclutador_id   BIGINT NOT NULL REFERENCES reclutadores(id) ON DELETE CASCADE,
  meta_individual INTEGER DEFAULT 0,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (campana_id, reclutador_id)
);

CREATE TABLE IF NOT EXISTS formadores (
  documento         VARCHAR(20) PRIMARY KEY,
  nombre_completo   VARCHAR(200) NOT NULL,
  sede_id           BIGINT REFERENCES sedes(id) ON DELETE SET NULL,
  campana_id        BIGINT REFERENCES campanas(id) ON DELETE SET NULL,
  cargo_contractual VARCHAR(150),
  cargo_funcional   VARCHAR(150),
  estado            VARCHAR(50) NOT NULL DEFAULT 'Activo'
    CHECK (estado IN ('Activo','Cese')),
  fecha_inicio      DATE,
  fecha_cese        DATE,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

