-- ── ASISTENCIAS Y EVALUACIONES ──────────────────────────────
CREATE TABLE IF NOT EXISTS asistencias_capacitacion (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  postulante_documento VARCHAR(30) NOT NULL REFERENCES postulantes(documento) ON DELETE CASCADE,
  grupo_codigo         VARCHAR(50) NOT NULL REFERENCES grupos_capacitacion(codigo) ON DELETE RESTRICT,
  fecha_asistencia     DATE NOT NULL,
  sigla_asistencia     VARCHAR(10) NOT NULL
    CHECK (sigla_asistencia IN ('A','I-OP','B','FI','FJ')),
  motivo_baja          VARCHAR(100) REFERENCES motivos_baja(motivo) ON DELETE RESTRICT,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (postulante_documento, grupo_codigo, fecha_asistencia),
  CHECK (
    (sigla_asistencia = 'B' AND motivo_baja IS NOT NULL) OR
    (sigla_asistencia != 'B' AND motivo_baja IS NULL)
  )
);

CREATE TABLE IF NOT EXISTS evaluaciones_capacitacion (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  postulante_documento  VARCHAR(30) NOT NULL REFERENCES postulantes(documento) ON DELETE CASCADE,
  grupo_codigo          VARCHAR(50) NOT NULL REFERENCES grupos_capacitacion(codigo) ON DELETE RESTRICT,
  nomina_id             UUID REFERENCES nominas(id) ON DELETE SET NULL,
  alfabetidad           NUMERIC(3,1) CHECK (alfabetidad BETWEEN 0 AND 10),
  orientacion_cliente   NUMERIC(3,1) CHECK (orientacion_cliente BETWEEN 0 AND 10),
  habilidades_contacto  NUMERIC(3,1) CHECK (habilidades_contacto BETWEEN 0 AND 10),
  resultado             VARCHAR(30) NOT NULL
    CHECK (resultado IN ('APROBADO','DESAPROBADO','NO DA EVALUAR')),
  observaciones         TEXT,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (postulante_documento, grupo_codigo)
);

