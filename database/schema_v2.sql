-- Lectura general para autenticados
DO $$ DECLARE t TEXT;
BEGIN
  FOREACH t IN ARRAY ARRAY['sedes','campanas','reclutadores','postulantes','nominas',
    'asistencias_capacitacion','evaluaciones_capacitacion','grupos_capacitacion','formadores','audit_logs']
  LOOP
    EXECUTE format('DROP POLICY IF EXISTS select_all ON %I', t);
    EXECUTE format('CREATE POLICY select_all ON %I FOR SELECT TO authenticated USING (true)', t);
  END LOOP;
END $$;

-- Escritura postulantes/nominas: admin + reclutador
CREATE POLICY insert_postulantes ON postulantes FOR INSERT TO authenticated
  WITH CHECK (EXISTS (SELECT 1 FROM perfiles WHERE id = auth.uid() AND rol IN ('admin','reclutador')));

CREATE POLICY update_postulantes ON postulantes FOR UPDATE TO authenticated
  USING (EXISTS (SELECT 1 FROM perfiles WHERE id = auth.uid() AND rol IN ('admin','reclutador')));

CREATE POLICY insert_nominas ON nominas FOR INSERT TO authenticated
  WITH CHECK (EXISTS (SELECT 1 FROM perfiles WHERE id = auth.uid() AND rol IN ('admin','reclutador')));

CREATE POLICY update_nominas ON nominas FOR UPDATE TO authenticated
  USING (EXISTS (SELECT 1 FROM perfiles WHERE id = auth.uid() AND rol IN ('admin','reclutador','formador')));

-- Asistencias: admin + formador
CREATE POLICY write_asistencias ON asistencias_capacitacion FOR ALL TO authenticated
  USING (EXISTS (SELECT 1 FROM perfiles WHERE id = auth.uid() AND rol IN ('admin','formador')))
  WITH CHECK (EXISTS (SELECT 1 FROM perfiles WHERE id = auth.uid() AND rol IN ('admin','formador')));

