-- ── PERSONA ─────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS postulantes (
  documento           VARCHAR(30) PRIMARY KEY,
  tipo_documento      VARCHAR(10) NOT NULL DEFAULT 'DNI'
    CHECK (tipo_documento IN ('DNI','CE','PASAPORTE')),
  apellido_paterno     VARCHAR(100) NOT NULL,
  apellido_materno     VARCHAR(100) NOT NULL,
  nombres              VARCHAR(150) NOT NULL,
  celular              VARCHAR(30),
  celular_referencia   VARCHAR(30),
  correo               VARCHAR(255),
  genero               VARCHAR(20) CHECK (genero IN ('MASCULINO','FEMENINO')),
  fecha_nacimiento     DATE,
  estado_civil         VARCHAR(50)
    CHECK (estado_civil IN ('SOLTERO','CASADO','DIVORCIADO','CONVIVIENTE','VIUDO')),
  n_hijos              INTEGER NOT NULL DEFAULT 0 CHECK (n_hijos >= 0),
  nivel_academico      VARCHAR(100),
  carrera              VARCHAR(150),
  nacionalidad         VARCHAR(80) DEFAULT 'PERUANA',
  lugar_residencia     VARCHAR(150),
  distrito_residencia  VARCHAR(100),
  direccion_domicilio  TEXT,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ── PROCESO DE NÓMINA (consolidado Excel) ───────────────────
CREATE TABLE IF NOT EXISTS nominas (
  id                      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  postulante_documento    VARCHAR(30) NOT NULL REFERENCES postulantes(documento) ON DELETE CASCADE,

  -- Reclutamiento
  periodo_reclutado       VARCHAR(10),
  semana_trabajo          INTEGER CHECK (semana_trabajo BETWEEN 1 AND 53),
  reclutador_id           BIGINT REFERENCES reclutadores(id) ON DELETE SET NULL,
  sede_id                 BIGINT REFERENCES sedes(id) ON DELETE SET NULL,
  campana_id              BIGINT REFERENCES campanas(id) ON DELETE SET NULL,
  fuente_oferta           VARCHAR(200),
  observacion_reclutamiento TEXT,

  -- Experiencia laboral
  exp_call_center         BOOLEAN,
  exp_tipo_campana        TEXT,
  exp_tiempo_campana      VARCHAR(80),
  exp_otra                TEXT,
  exp_tiempo_otra         VARCHAR(80),

  -- Capacitación / pipeline
  grupo_codigo            VARCHAR(50) REFERENCES grupos_capacitacion(codigo) ON DELETE SET NULL,
  modalidad               modalidad_tipo,
  condicion               VARCHAR(100),
  horario_gestion         VARCHAR(100),
  descanso                VARCHAR(100),
  envio_dni               DATE,
  test_psicologico        VARCHAR(50),
  validacion_pc           VARCHAR(50),
  evaluacion_dia_0        VARCHAR(50),
  fecha_inicio_capacitacion DATE,
  fecha_fin_capacitacion  DATE,
  fecha_conexion_ojt      DATE,
  fecha_conexion_op       DATE,
  pago_capacitacion       BOOLEAN DEFAULT FALSE,

  -- Contrato y compensación
  tipo_contratacion       VARCHAR(80),
  razon_social            VARCHAR(150),
  remuneracion            NUMERIC(10,2),
  bono_variable           NUMERIC(10,2),
  bono_movilidad          NUMERIC(10,2),
  bono_bienvenida         NUMERIC(10,2),
  bono_permanencia        NUMERIC(10,2),
  bono_asistencia_perfecta NUMERIC(10,2),
  cargo_contractual       VARCHAR(150),

  -- Seguimiento día 0 / día 1
  dia_0                   DATE,
  dia_0_obs               TEXT,
  status_dia_1            VARCHAR(80),
  dia_1                   DATE,
  dia_1_obs               TEXT,

  -- Estado del proceso
  estado                  nomina_estado NOT NULL DEFAULT 'RECLUTADO',
  activo                  BOOLEAN NOT NULL DEFAULT TRUE,

  created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW()
