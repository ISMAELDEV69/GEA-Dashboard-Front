-- Perfiles (mantener existente)
DROP POLICY IF EXISTS select_perfiles ON perfiles;
DROP POLICY IF EXISTS insert_perfiles ON perfiles;
DROP POLICY IF EXISTS update_perfiles ON perfiles;

CREATE POLICY select_perfiles ON perfiles FOR SELECT TO authenticated USING (true);
CREATE POLICY insert_perfiles ON perfiles FOR INSERT WITH CHECK (true);
CREATE POLICY update_perfiles ON perfiles FOR UPDATE TO authenticated
  USING (auth.uid() = id OR EXISTS (SELECT 1 FROM perfiles p WHERE p.id = auth.uid() AND p.rol = 'admin'))
  WITH CHECK (auth.uid() = id OR EXISTS (SELECT 1 FROM perfiles p WHERE p.id = auth.uid() AND p.rol = 'admin'));

-- get_my_profile (auth)
CREATE OR REPLACE FUNCTION get_my_profile()
RETURNS perfiles AS $$
DECLARE result perfiles; v_meta JSONB; v_rol TEXT;
BEGIN
  SELECT * INTO result FROM perfiles WHERE id = auth.uid();
  IF FOUND THEN RETURN result; END IF;
  v_meta := COALESCE(auth.jwt()->'user_metadata', '{}'::jsonb);
  v_rol := v_meta->>'rol';
  INSERT INTO perfiles (id, nombre, rol) VALUES (
    auth.uid(),
    COALESCE(v_meta->>'nombre', split_part(COALESCE(auth.jwt()->>'email',''), '@', 1), 'Usuario'),
    CASE WHEN v_rol IN ('admin','reclutador','formador','visor') THEN v_rol::app_role ELSE 'visor'::app_role END
  ) ON CONFLICT (id) DO NOTHING RETURNING * INTO result;
  IF NOT FOUND THEN SELECT * INTO result FROM perfiles WHERE id = auth.uid(); END IF;
  RETURN result;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;
GRANT EXECUTE ON FUNCTION get_my_profile() TO authenticated;
